CREATE TABLE IF NOT EXISTS resume_processing_jobs (
  id CHAR(36) PRIMARY KEY,
  owner_id VARCHAR(128) NOT NULL,
  idempotency_key CHAR(64) NOT NULL,
  status ENUM('queued','processing','awaiting_review','completed','failed','dead_letter','cancelled') NOT NULL DEFAULT 'queued',
  original_path VARCHAR(1024) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(255) NOT NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  sha256 CHAR(64) NOT NULL,
  page_count SMALLINT UNSIGNED NULL,
  attempt_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 3,
  processing_timeout_seconds INT UNSIGNED NOT NULL DEFAULT 900,
  lease_owner VARCHAR(128) NULL,
  lease_expires_at DATETIME(6) NULL,
  heartbeat_at DATETIME(6) NULL,
  page_checkpoint SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  chunk_checkpoint SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  extracted_result JSON NULL,
  ai_result JSON NULL,
  confirmed_result JSON NULL,
  error_message TEXT NULL,
  started_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_resume_processing_owner_idempotency (owner_id, idempotency_key),
  KEY ix_resume_processing_status_updated (status, updated_at),
  KEY ix_resume_processing_owner_created (owner_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

